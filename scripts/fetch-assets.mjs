// Reproducible asset vendoring: reads asset-spec.json, downloads each entry into
// public/assets/, verifies it, and regenerates src/data/assets.js + LICENSES.md.
//
//   node scripts/fetch-assets.mjs
//
// asset-spec.json entry shape:
//   { "key": "hero", "url": "https://.../hero.png", "type": "image|spritesheet|audio|json",
//     "frameWidth": 16, "frameHeight": 16, "license": "CC0", "credit": "Kenney — kenney.nl",
//     "source": "https://original-page-url" }
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SPEC = path.join(ROOT, 'asset-spec.json');
const OUT_DIR = path.join(ROOT, 'public', 'assets');

if (!fs.existsSync(SPEC)) {
  console.error('missing asset-spec.json');
  process.exit(1);
}

const spec = JSON.parse(fs.readFileSync(SPEC, 'utf8'));
const manifest = [];
const credits = [];
const failures = [];

fs.mkdirSync(path.join(OUT_DIR, 'sprites'), { recursive: true });
fs.mkdirSync(path.join(OUT_DIR, 'audio'), { recursive: true });
fs.mkdirSync(path.join(OUT_DIR, 'fonts'), { recursive: true });

for (const entry of spec) {
  if (entry.type === 'text') {
    // license / tilesheet notes: keep a local copy for provenance, do not ship in the manifest
    const dest = path.join(ROOT, 'licenses', entry.file || `${entry.key}.txt`);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    try {
      const res = await fetch(entry.url, { redirect: 'follow', signal: AbortSignal.timeout(30000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
      console.log(`lic  ${entry.key.padEnd(14)} -> licenses/${path.basename(dest)}`);
    } catch (err) {
      failures.push({ key: entry.key, url: entry.url, error: String(err.message || err) });
      console.log(`FAIL ${entry.key.padEnd(14)} ${err.message}`);
    }
    continue;
  }
  const ext = (entry.url.match(/\.(png|jpg|jpeg|webp|ogg|mp3|wav|json|atlas|fnt|ttf)$/i) || [])[1] || 'bin';
  const folder = entry.type === 'audio' ? 'audio' : ext === 'ttf' ? 'fonts' : 'sprites';
  const dest = path.join(OUT_DIR, folder, `${entry.key}.${ext}`);
  if (!process.argv.includes('--force') && fs.existsSync(dest) && fs.statSync(dest).size > 64) {
    manifest.push({
      key: entry.key,
      type: entry.type || 'image',
      url: `/assets/${folder}/${path.basename(dest)}`,
      frameWidth: entry.frameWidth,
      frameHeight: entry.frameHeight,
      spacing: entry.spacing,
      margin: entry.margin,
      family: entry.family,
      credit: entry.credit,
    });
    credits.push(entry);
    console.log(`cached ${entry.key.padEnd(14)} ${(fs.statSync(dest).size / 1024).toFixed(1)}KB`);
    continue;
  }
  if (entry.delayMs) await new Promise((r) => setTimeout(r, entry.delayMs));
  try {
    const res = await fetch(entry.url, { redirect: 'follow', signal: AbortSignal.timeout(60000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 32) throw new Error(`too small (${buf.length}B) — probably an error page`);
    const isImage = buf.slice(1, 4).toString('latin1') === 'PNG';
    const isOgg = buf.slice(0, 4).toString('latin1') === 'OggS';
    const isMp3 = buf.slice(0, 3).toString('latin1') === 'ID3' || buf[0] === 0xff;
    const isTtf = buf.slice(0, 4).toString('hex') === '00010000';
    if (!isImage && !isOgg && !isMp3 && !isTtf) {
      throw new Error(`body is not the expected binary (starts ${buf.slice(0, 12).toString('latin1').replace(/\n/g, ' ')})`);
    }
    fs.writeFileSync(dest, buf);
    manifest.push({
      key: entry.key,
      type: entry.type || 'image',
      url: `/assets/${folder}/${path.basename(dest)}`,
      frameWidth: entry.frameWidth,
      frameHeight: entry.frameHeight,
      spacing: entry.spacing,
      margin: entry.margin,
      family: entry.family,
      credit: entry.credit,
    });
    credits.push(entry);
    console.log(`ok   ${entry.key.padEnd(14)} ${(buf.length / 1024).toFixed(1)}KB  ${entry.license || 'unknown license'}`);
  } catch (err) {
    failures.push({ key: entry.key, url: entry.url, error: String(err.message || err) });
    console.log(`FAIL ${entry.key.padEnd(14)} ${err.message}`);
  }
}

const banner = '// GENERATED by scripts/fetch-assets.mjs — do not edit by hand.\n'
  + '// Every entry here is vendored open-licensed art/audio; see LICENSES.md for terms.\n';
const body = `export const ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n\nexport const CREDITS = ${JSON.stringify(credits.map((c) => ({ key: c.key, license: c.license, credit: c.credit, source: c.source })), null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, 'src', 'data', 'assets.js'), banner + body);

const rows = credits.map((c) => `| ${c.key} | ${c.license || '?'} | ${c.credit || ''} | ${c.source || c.url} |`);
fs.writeFileSync(path.join(ROOT, 'LICENSES.md'), `# Third-party assets

| key | license | author / pack | source |
| --- | --- | --- | --- |
${rows.join('\n')}

${failures.length ? `## Skipped (unreachable at fetch time)\n\n${failures.map((f) => `- \`${f.key}\` — ${f.error}`).join('\n')}\n` : ''}
All other code in this repository is original. Procedural fallback textures in
\`src/systems/TextureFactory.js\` keep the game running with zero external files.
`);

console.log(`\nwrote ${manifest.length} manifest entries, ${failures.length} failures -> src/data/assets.js`);
